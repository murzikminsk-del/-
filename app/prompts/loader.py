from functools import lru_cache # lru_cache нужен, чтобы функция запоминала результат
from pathlib import Path # для работы с путями к файлам

from jinja2 import Template # jinja2 нужен для шаблонов, чтобы можно было подставлять переменные в текст

PROMPT_DIR = Path(__file__).parent # папка, где хранятся шаблоны для промптов, то есть папка prompts, в которой находится этот файл loader.py 


# функция принимает имя файла промпта в виде строки, например, "system_v1.j2" и любые переменные для подстановки в шаблон. Она читает текст из файла, создает шаблон и рендерит его с переданными переменными. Результат возвращается в виде строки.
@lru_cache(maxsize=8) # maxsize=8 означает, что функция будет запоминать результаты для 8 разных наборов аргументов. 
def render_prompt(file_name: str, **context) -> str:
    prompt_path = PROMPT_DIR / file_name # формируем полный путь к файлу промпта, объединяя папку и имя файла
    
    text = prompt_path.read_text(encoding="utf-8") # открываем файл и читаем его содержимое как текст, указывая кодировку utf-8 для правильного чтения текста
    
    return Template(text).render(**context) # превращаем обычный текст в Jinja2-шаблон и подставляем переменные из context. Результат возвращаем в виде строки.
    